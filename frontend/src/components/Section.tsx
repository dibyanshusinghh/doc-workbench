import type { ReactNode } from 'react';
import type { DocumentRef } from '../lib/documents';

export type Origin = 'ai' | 'extracted';

/** Labels content as AI interpretation or extracted fact — shown on every results section. */
export function OriginBadge({ origin }: { origin: Origin }) {
  return origin === 'ai' ? (
    <span className="badge badge-ai" title="Generated by the AI model — verify against the sources">
      AI interpretation
    </span>
  ) : (
    <span className="badge badge-extracted" title="Taken directly from the document text">
      Extracted fact
    </span>
  );
}

/** Shows which document supports a value or finding, e.g. "D1 · application.txt". */
export function SourceTag({ docRef }: { docRef: DocumentRef }) {
  return (
    <span className="source-tag" title={docRef.name}>
      <strong>{docRef.label}</strong> {docRef.name}
    </span>
  );
}

interface SectionProps {
  title: string;
  origin?: Origin;
  actions?: ReactNode;
  children: ReactNode;
}

export function Section({ title, origin, actions, children }: SectionProps) {
  return (
    <section className="card">
      <div className="section-header">
        <h3>{title}</h3>
        {origin && <OriginBadge origin={origin} />}
        {actions && <div className="section-actions">{actions}</div>}
      </div>
      {children}
    </section>
  );
}
